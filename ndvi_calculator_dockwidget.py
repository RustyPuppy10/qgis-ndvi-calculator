import os

from qgis.PyQt import QtGui, QtWidgets, uic
from qgis.PyQt.QtCore import pyqtSignal

from qgis.core import QgsProject, QgsRasterLayer
from qgis.analysis import QgsRasterCalculator, QgsRasterCalculatorEntry
from qgis.PyQt.QtWidgets import QFileDialog, QMessageBox

FORM_CLASS, _ = uic.loadUiType(
    os.path.join(
        os.path.dirname(__file__),
        'ndvi_calculator_dockwidget_base.ui'),
    from_imports=True,
    import_from='ndvi_calculator')


class NdviCalculatorDockWidget(QtWidgets.QDockWidget, FORM_CLASS):

    closingPlugin = pyqtSignal()

    def __init__(self, parent=None):
        """Constructor."""
        super(NdviCalculatorDockWidget, self).__init__(parent)

        # Подключаем интерфейс из Qt Designer
        self.setupUi(self)

        # Заполняем списки растровыми слоями из QGIS
        self.populate_raster_layers()

        # Подключаем кнопку расчёта
        self.pushButtonCalculate.clicked.connect(
            self.calculate_ndvi
        )

    def populate_raster_layers(self):
        """Добавляет растры в списки, но не выбирает канал автоматически."""
        from qgis.core import QgsProject, QgsRasterLayer

        layers = QgsProject.instance().mapLayers().values()

        raster_layers = [
            layer for layer in layers
            if isinstance(layer, QgsRasterLayer) and layer.isValid()
        ]

        self.comboBoxRed.clear()
        self.comboBoxNir.clear()

        # Первый пункт — подсказка вместо автоматически выбранного растра
        self.comboBoxRed.addItem("Выберите канал Red...", None)
        self.comboBoxNir.addItem("Выберите канал NIR...", None)

        for layer in raster_layers:
            self.comboBoxRed.addItem(layer.name(), layer.id())
            self.comboBoxNir.addItem(layer.name(), layer.id())

        # Оставляем подсказку выбранной при открытии
        self.comboBoxRed.setCurrentIndex(0)
        self.comboBoxNir.setCurrentIndex(0)

    def calculate_ndvi(self):
        # Получаем выбранные растровые слои по их ID
        project = QgsProject.instance()

        red_id = self.comboBoxRed.currentData()
        nir_id = self.comboBoxNir.currentData()

        red_layer = project.mapLayer(red_id) if red_id else None
        nir_layer = project.mapLayer(nir_id) if nir_id else None

        # Проверяем выбор слоёв
        if not isinstance(red_layer, QgsRasterLayer) or not red_layer.isValid():
            QMessageBox.warning(
                self, "NDVI Calculator",
                "Выберите корректный растровый слой Red."
            )
            return

        if not isinstance(nir_layer, QgsRasterLayer) or not nir_layer.isValid():
            QMessageBox.warning(
                self, "NDVI Calculator",
                "Выберите корректный растровый слой NIR."
            )
            return

        if red_layer.id() == nir_layer.id():
            QMessageBox.warning(
                self, "NDVI Calculator",
                "Для Red и NIR нужно выбрать разные растры."
            )
            return

        # Выбираем место сохранения результата
        output_path, _ = QFileDialog.getSaveFileName(
            self,
            "Сохранить результат NDVI",
            "ndvi.tif",
            "GeoTIFF (*.tif)"
        )

        if not output_path:
            return

        if not output_path.lower().endswith(".tif"):
            output_path += ".tif"

        # Создаём ссылки на первый канал каждого растра
        red_entry = QgsRasterCalculatorEntry()
        red_entry.ref = "red@1"
        red_entry.raster = red_layer
        red_entry.bandNumber = 1

        nir_entry = QgsRasterCalculatorEntry()
        nir_entry.ref = "nir@1"
        nir_entry.raster = nir_layer
        nir_entry.bandNumber = 1

        entries = [red_entry, nir_entry]

        # Landsat Collection 2 Level-2 Surface Reflectance:
        # отражательная способность = DN * 0.0000275 - 0.2
        formula = (
            "((nir@1 * 0.0000275 - 0.2) - "
            "(red@1 * 0.0000275 - 0.2)) / "
            "((nir@1 * 0.0000275 - 0.2) + "
            "(red@1 * 0.0000275 - 0.2))"
        )

        calculator = QgsRasterCalculator(
            formula,
            output_path,
            "GTiff",
            red_layer.extent(),
            red_layer.crs(),
            red_layer.width(),
            red_layer.height(),
            entries,
            project.transformContext()
        )

        calculator.setNoDataValue(-9999.0)

        result = calculator.processCalculation()

        if result != QgsRasterCalculator.Result.Success:
            QMessageBox.critical(
                self,
                "Ошибка расчёта NDVI",
                calculator.lastError()
            )
            return

        # Добавляем рассчитанный растр в проект
        ndvi_layer = QgsRasterLayer(output_path, "NDVI")

        if not ndvi_layer.isValid():
            QMessageBox.critical(
                self, "Ошибка",
                "Расчёт завершился, но результат не удалось открыть."
            )
            return

        project.addMapLayer(ndvi_layer)

        QMessageBox.information(
            self,
            "NDVI Calculator",
            "Расчёт NDVI завершён!\n"
            f"Результат сохранён:\n{output_path}"
        )



    def closeEvent(self, event):
        self.closingPlugin.emit()
        event.accept()
